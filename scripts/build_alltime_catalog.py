def build():
    players = []
    teams_index = {}
    seen_ids = set()
    for tid, (slug, school, plist) in sorted(RAW.items(), key=lambda x: x[1][1].lower()):
        teams_index[tid] = {"id": tid, "slug": slug, "name": school, "count": 0}
        for name, pos, ovr in plist:
            ovr = int(max(40, min(99, ovr)))
            pid = make_id(slug, name)
            # Ensure unique ids across catalog
            base = pid
            n = 2
            while pid in seen_ids:
                pid = f"{base}-{n}"
                n += 1
            seen_ids.add(pid)
            players.append({
                "id": pid,
                "n": name,
                "p": pos,
                "schoolId": tid,
                "school": school,
                "ovr": ovr,
                "cost": cost_for_ovr(ovr),
            })
            teams_index[tid]["count"] += 1
    players.sort(key=lambda x: (-x["ovr"], x["school"], x["n"]))
    return {
        "version": 1,
        "generatedBy": "scripts/build_alltime_catalog.py",
        "notes": "Real historical CFB players only. OVR is video-game style (40-99). Cost scales with OVR.",
        "positions": ["QB","RB","WR","TE","OL","DL","LB","DB","K","P"],
        "costFormula": "round(8 + (ovr-39)^2 * 0.22)",
        "playerCount": len(players),
        "teamCount": len(teams_index),
        "teams": teams_index,
        "players": players,
    }

def main():
    data = build()
    outp = ROOT / "data" / "alltime-players.json"
    outp.write_text(json.dumps(data, separators=(",", ":")) + "\n")
    # Also pretty sample stats
    print(f"Wrote {outp}")
    print(f"Players: {data['playerCount']} across {data['teamCount']} teams")
    by_pos = {}
    for p in data["players"]:
        by_pos[p["p"]] = by_pos.get(p["p"], 0) + 1
    print("By position:", dict(sorted(by_pos.items())))
    # Sample prices
    for o in (50, 70, 85, 95, 99):
        print(f"  OVR {o} -> {cost_for_ovr(o)} coins")
    top = data["players"][:8]
    print("Top OVRs:", [(p["n"], p["school"], p["ovr"], p["cost"]) for p in top])

if __name__ == "__main__":
    main()
