def cost_for_ovr(ovr: int) -> int:
    x = max(0, int(ovr) - 39)
    return int(round(8 + (x ** 2) * 0.22))

def make_id(slug: str, name: str) -> str:
    s = (
        name.lower()
        .replace(".", "")
        .replace("'", "")
        .replace("'", "")
        .replace(" ", "-")
        .replace(",", "")
    )
    return f"{slug}-{s}"

RAW: dict[str, tuple[str, str, list[tuple[str, str, int]]]] = {}

def T(tid: str, slug: str, school: str, players: list[tuple[str, str, int]]) -> None:
    best: dict[str, tuple[str, str, int]] = {}
    for n, p, o in players:
        if n not in best or o > best[n][2]:
            best[n] = (n, p, int(o))
    RAW[tid] = (slug, school, list(best.values()))

